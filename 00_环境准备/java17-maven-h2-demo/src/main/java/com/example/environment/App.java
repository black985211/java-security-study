package com.example.environment;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

public class App {

    public static void main(String[] args) throws SQLException {
        DatabaseConfig config = DatabaseConfig.load();

        try (Connection connection = DriverManager.getConnection(
                config.url(), config.username(), config.password())) {
            createTable(connection);
            insertStudent(connection, "Java 17 环境验收");
            printStudents(connection);
        }
    }

    static void createTable(Connection connection) throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS student (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL
                )
                """;

        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    static void insertStudent(Connection connection, String name) throws SQLException {
        String sql = "INSERT INTO student (name) VALUES (?)";

        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, name);
            statement.executeUpdate();
        }
    }

    static void printStudents(Connection connection) throws SQLException {
        String sql = "SELECT id, name FROM student ORDER BY id";

        try (Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(sql)) {
            while (resultSet.next()) {
                long id = resultSet.getLong("id");
                String name = resultSet.getString("name");
                System.out.printf("H2 连接成功：id=%d, name=%s%n", id, name);
            }
        }
    }
}
